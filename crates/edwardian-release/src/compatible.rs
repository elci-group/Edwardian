//! Compatible release mode: additive scaffolding on a development branch.

use super::{DepMapping, TARGET_SECTION_HEADER, capability_evidence, render_dep_section};
use edwardian_core::Platform;
use edwardian_engine::{AnalysisReport, PipelineConfig, inventory};
use serde::Serialize;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

pub(crate) fn module_name(capability: &str) -> String {
    capability.replace('-', "_").replace(':', "_")
}

pub(crate) fn trait_name(required_interface: &str) -> Option<&str> {
    if !required_interface.contains("pub trait ") {
        return None;
    }
    let rest = required_interface.split("trait ").nth(1)?;
    Some(
        rest.trim_start()
            .split(|c: char| c == ' ' || c == '<' || c == '{')
            .next()?
            .trim(),
    )
}

/// All files the branch would add, relative to the repo root. Deterministic:
/// proposals in report order, deps sorted.
pub fn scaffold_files(report: &AnalysisReport) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut mod_decls = String::from("//! Platform capability backends (generated by edwardian compatible release).\n");
    for p in &report.proposals {
        let m = module_name(&p.capability);
        let trait_nm = trait_name(&p.required_interface).unwrap_or("Capability");
        let mut trait_file = String::new();
        if p.required_interface.contains("Path") {
            trait_file.push_str("use std::path::Path;\n\n");
        }
        trait_file.push_str(&format!(
            "//! Platform abstraction for `{}` ({}).\n\n{}\n",
            p.capability, p.id, p.required_interface
        ));
        files.push((format!("src/platform/{}.rs", m), trait_file));

        files.push((
            format!("src/platform/{}_unix.rs", m),
            format!(
                "//! Unix backend for `{}` ({}): adapt the existing unix implementation\n//! to the `{}` trait.\n",
                p.capability, p.id, trait_nm
            ),
        ));
        files.push((
            format!("src/platform/{}_windows.rs", m),
            format!(
                "//! Windows backend for `{}` ({}): STUB — not yet implemented.\n//!\n//! Invariant from {}: {}\n\npub fn not_yet_implemented() -> ! {{\n    unimplemented!(\"{}: windows backend for `{}`\")\n}}\n",
                p.capability,
                p.id,
                p.id,
                p.compatibility_invariant,
                p.id,
                p.capability
            ),
        ));
        mod_decls.push_str(&format!(
            "\npub mod {};\n\n#[cfg(unix)]\npub mod {}_unix;\n#[cfg(windows)]\npub mod {}_windows;\n",
            m, m, m
        ));
    }
    files.push(("src/platform/mod.rs".to_string(), mod_decls));
    files
}

pub fn compat_manifest(report: &AnalysisReport, branch: &str, deps: &[DepMapping]) -> String {
    let mut md = String::from("# Edwardian compatible-release branch\n\n");
    md.push_str(&format!("Branch: `{}`\n", branch));
    md.push_str(&format!("Target: {}\n\n", report.target.label()));
    md.push_str("## Proposals\n\n");
    for p in &report.proposals {
        md.push_str(&format!(
            "- **{}** (`{}`): {}\n",
            p.id, p.capability, p.required_impl
        ));
    }
    md.push_str("\n## Added dependencies\n\n");
    if deps.is_empty() {
        md.push_str("_None._\n");
    } else {
        for d in deps {
            md.push_str(&format!("- `{} = \"{}\"` ({})\n", d.crate_name, d.version, TARGET_SECTION_HEADER));
        }
    }
    md.push_str("\n## Validation plan\n\n");
    md.push_str("- Linux build passes (cargo build)\n");
    md.push_str("- Windows build passes (cargo build --target x86_64-pc-windows-msvc)\n");
    for p in &report.proposals {
        md.push_str(&format!("- {} invariant holds: {}\n", p.id, p.compatibility_invariant));
    }
    md.push_str("- CI matrix (ubuntu-latest, windows-latest) passes\n");
    md
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct CompatibleReport {
    pub mode: &'static str,
    pub applied_via: String,
    pub branch: String,
    pub proposals: usize,
    pub deps: usize,
    pub written_paths: Vec<String>,
    pub note: String,
    pub nothing_to_do: bool,
}

fn git(args: &[&str], cwd: &Path) -> Result<String, String> {
    let out = Command::new("git")
        .args(args)
        .current_dir(cwd)
        .output()
        .map_err(|e| format!("git unavailable: {}", e))?;
    if !out.status.success() {
        return Err(format!(
            "git {:?} failed: {}",
            args,
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn git_ok(args: &[&str], cwd: &Path) -> bool {
    git(args, cwd).is_ok()
}

/// Mode 2: compatible release. Main-branch files are never modified: all
/// content is additive on a development branch (git work tree permitting),
/// otherwise written to `<out>/compat-branch/` as a fallback.
pub fn compatible(
    report: &AnalysisReport,
    source: &Path,
    out: &Path,
    branch_name: Option<&str>,
    no_git: bool,
) -> io::Result<CompatibleReport> {
    let branch = branch_name
        .map(str::to_string)
        .unwrap_or_else(|| format!("edwardian/compat-{}", report.target.label().to_lowercase()));
    let deps: Vec<DepMapping> = if report.target == Platform::Windows {
        super::resolve_deps(report, report.target)
    } else {
        Vec::new()
    };

    if report.proposals.is_empty() {
        return Ok(CompatibleReport {
            mode: "compatible",
            applied_via: "none".to_string(),
            branch,
            proposals: 0,
            deps: 0,
            written_paths: Vec::new(),
            note: "nothing to do: no proposals generated".to_string(),
            nothing_to_do: true,
        });
    }

    let files = scaffold_files(report);
    let manifest = compat_manifest(report, &branch, &deps);
    let mut written: Vec<String> = files.iter().map(|(p, _)| p.clone()).collect();
    let manifest_rel = "EDWARDIAN-COMPAT.md".to_string();
    written.push(manifest_rel.clone());
    written.sort();

    let mut all_files = files.clone();
    // Cargo.toml patch (existing file -> branch-only content).
    let manifest_patch = if deps.is_empty() {
        None
    } else {
        let cargo_path = source.join("Cargo.toml");
        if cargo_path.is_file() {
            let existing = fs::read_to_string(&cargo_path)?;
            let section = render_dep_section(&existing, &deps);
            if section.is_empty() {
                None
            } else {
                Some((existing + &section, "Cargo.toml".to_string()))
            }
        } else {
            None
        }
    };
    if let Some((_, ref rel)) = manifest_patch {
        if !written.contains(rel) {
            written.push(rel.clone());
            written.sort();
        }
    }

    let use_git = !no_git
        && report.discovery.repo_root == source.display().to_string()
        && git_ok(&["rev-parse", "--is-inside-work-tree"], source);
    let evidence_note = deps
        .iter()
        .map(|d| format!("{}: {}", d.crate_name, capability_evidence(report, d.capability).join(", ")))
        .collect::<Vec<_>>()
        .join("; ");

    if use_git {
        match apply_git_branch(source, &branch, &all_files, manifest_patch.as_ref(), &manifest, &written, report.proposals.len(), deps.len()) {
            Ok(()) => {
                return Ok(CompatibleReport {
                    mode: "compatible",
                    applied_via: "git".to_string(),
                    branch,
                    proposals: report.proposals.len(),
                    deps: deps.len(),
                    written_paths: written,
                    note: format!("committed on branch; dependencies backed by evidence ({})", evidence_note),
                    nothing_to_do: false,
                });
            }
            Err(e) => {
                // Fall through to the out-dir fallback; leave any partial git
                // state untouched (never delete branches).
                all_files = scaffold_files(report);
                return fallback(report, source, out, &branch, &all_files, manifest_patch.as_ref(), &manifest, &written, deps.len(), &format!("git failed ({e}); wrote branch content to disk instead"));
            }
        }
    }

    fallback(report, source, out, &branch, &all_files, manifest_patch.as_ref(), &manifest, &written, deps.len(), "not a git work tree or --no-git given; wrote branch content to disk")
}

fn apply_git_branch(
    source: &Path,
    branch: &str,
    files: &[(String, String)],
    manifest_patch: Option<&(String, String)>,
    manifest: &str,
    written: &[String],
    n_proposals: usize,
    n_deps: usize,
) -> Result<(), String> {
    git(&["checkout", "-b", branch], source)?;
    for (rel, content) in files {
        let path: PathBuf = source.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(&path, content).map_err(|e| e.to_string())?;
    }
    if let Some((content, rel)) = manifest_patch {
        fs::write(source.join(rel), content).map_err(|e| e.to_string())?;
    }
    fs::write(source.join("EDWARDIAN-COMPAT.md"), manifest).map_err(|e| e.to_string())?;
    let mut add_args: Vec<&str> = vec!["add", "--"];
    add_args.extend(written.iter().map(|s| s.as_str()));
    git(&add_args, source)?;
    let msg = format!(
        "edwardian: windows compatibility scaffolding ({} proposals, {} deps)",
        n_proposals, n_deps
    );
    git(
        &[
            "-c", "user.name=edwardian", "-c", "user.email=edwardian@localhost",
            "commit", "-m", &msg,
        ],
        source,
    )?;
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn fallback(
    report: &AnalysisReport,
    source: &Path,
    out: &Path,
    branch: &str,
    files: &[(String, String)],
    manifest_patch: Option<&(String, String)>,
    manifest: &str,
    written: &[String],
    n_deps: usize,
    note: &str,
) -> io::Result<CompatibleReport> {
    let dir = out.join("compat-branch");
    fs::create_dir_all(&dir)?;
    // Mirror the repo content the branch builds on, then overlay additions.
    let config = PipelineConfig {
        target: report.target,
        ..PipelineConfig::default()
    };
    let (inv, _b, _l) = inventory(source, &config)?;
    for rec in &inv {
        let from = source.join(&rec.path);
        let to = dir.join(&rec.path);
        if let Some(parent) = to.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::copy(&from, &to)?;
    }
    for (rel, content) in files {
        let path = dir.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, content)?;
    }
    if let Some((content, rel)) = manifest_patch {
        fs::write(dir.join(rel), content)?;
    }
    fs::write(dir.join("EDWARDIAN-COMPAT.md"), manifest)?;
    Ok(CompatibleReport {
        mode: "compatible",
        applied_via: "fallback".to_string(),
        branch: branch.to_string(),
        proposals: report.proposals.len(),
        deps: n_deps,
        written_paths: written.to_vec(),
        note: note.to_string(),
        nothing_to_do: false,
    })
}
